def calculate_personal_code(birth_date: str) -> int:
    """Личный код (день + месяц → всегда 1-9)"""
    day, month, _ = map(int, birth_date.split('.'))
    total = sum(int(d) for d in str(day)) + sum(int(d) for d in str(month))
    while total > 9:
        total = sum(int(d) for d in str(total))
    return total

def get_relevant_year(birth_date: str, selected_month: int) -> int:
    """Определяет год для расчёта на основе ВЫБРАННОГО месяца (не текущего!)"""
    _, month_birth, _ = map(int, birth_date.split('.'))
    current_year = datetime.now().year  # 2025
    
    # Если выбранный месяц ИДЁТ ПОСЛЕ месяца рождения → берём текущий год (2025)
    if selected_month > month_birth:
        return current_year
    # Если выбранный месяц РАНЬШЕ месяца рождения → берём предыдущий год (2024)
    elif selected_month < month_birth:
        return current_year - 1
    # Если выбран тот же месяц → всегда текущий год (2025)
    else:
        return current_year

def calculate_year_energy(personal_code: int, birth_date: str) -> int:
    """Энергия года (только 1-9) с учетом персонального года"""
    # Используем январь (month=1) для определения персонального года
    relevant_year = get_relevant_year(birth_date, 1)  # <- Добавлен параметр 1
    total = personal_code + sum(int(d) for d in str(relevant_year))
    while total > 9:
        total = sum(int(d) for d in str(total))
    return total

def calculate_month_energy(personal_code: int, birth_date: str, month: int) -> int:
    """Энергия месяца = (личный код + сумма цифр года) + номер месяца"""
    # Шаг 1: Получаем актуальный год для выбранного месяца
    relevant_year = get_relevant_year(birth_date, month)
    
    # Шаг 2: Сумма цифр года (2025 → 2+0+2+5=9, 2024 → 8)
    year_sum = sum(int(d) for d in str(relevant_year))
    
    # Шаг 3: Личный код + сумма цифр года (сводим к 1-9)
    energy_year = personal_code + year_sum
    while energy_year > 9 and energy_year != 11:  # Сохраняем 11!
        energy_year = sum(int(d) for d in str(energy_year))
    
    # Шаг 4: Добавляем номер месяца
    total = energy_year + month
    return 11 if total == 11 else sum(int(d) for d in str(total))  # Сводим к 1-9, кроме 11

